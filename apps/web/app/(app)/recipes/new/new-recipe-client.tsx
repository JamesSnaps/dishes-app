"use client";

import { useState, useEffect } from "react";
import { Globe, Info } from "lucide-react";
import { createRecipe } from "@/app/actions/recipes";
import { RecipeForm, type RecipeFormDefaults } from "../_components/recipe-form";
import type { ImageStyleValue } from "@/lib/image-styles";
import { AiConcierge } from "../_components/ai-concierge";
import { PhotoImportModal } from "../_components/photo-import-modal";
import { WebImportModal } from "../_components/web-import-modal";
import type { GeneratedRecipe } from "@/lib/ai/recipe-generation";
import type { WebImportResult } from "@/lib/recipe-web-import";

interface NewRecipeClientProps {
  hasAi: boolean;
  defaultImageStyle?: ImageStyleValue;
  allTags?: string[];
  /** A recipe page link handed in via `?importUrl=` (bookmarklet, share sheet). */
  importUrl?: string;
}

const VIA_LABEL: Record<NonNullable<WebImportResult["via"]>, string> = {
  "recipe-data": "Read from the page's recipe data.",
  "recipe-data+ai": "Read from the page's recipe data and tidied by AI.",
  ai: "Read from the page by AI — double-check the quantities.",
};

export function NewRecipeClient({ hasAi, defaultImageStyle, allTags = [], importUrl }: NewRecipeClientProps) {
  const [defaults, setDefaults] = useState<RecipeFormDefaults>({});
  const [formKey, setFormKey] = useState(0);
  const [webImport, setWebImport] = useState<{ host: string; via?: WebImportResult["via"]; notice?: string } | null>(null);

  // Pick up a draft generated by the AI Concierge page
  useEffect(() => {
    const stored = sessionStorage.getItem("ai_draft");
    if (!stored) return;
    sessionStorage.removeItem("ai_draft");
    try {
      const parsed = JSON.parse(stored) as RecipeFormDefaults;
      setDefaults(parsed);
      setFormKey((k) => k + 1);
    } catch {
      // ignore malformed draft
    }
  }, []);

  function handleRecipeGenerated(generated: RecipeFormDefaults) {
    setDefaults(generated);
    setFormKey((k) => k + 1);
    setWebImport(null);
  }

  function handlePhotoImport(recipe: GeneratedRecipe) {
    // GeneratedRecipe is structurally compatible with RecipeFormDefaults
    setDefaults(recipe as RecipeFormDefaults);
    setFormKey((k) => k + 1);
    setWebImport(null);
  }

  function handleWebImport(draft: RecipeFormDefaults, info: Pick<WebImportResult, "via" | "notice">) {
    setDefaults(draft);
    setFormKey((k) => k + 1);
    let host = "";
    try {
      host = new URL(draft.sourceUrl ?? "").hostname.replace(/^www\./, "");
    } catch {
      // no usable source link — the banner just omits the site name
    }
    setWebImport({ host, ...info });
  }

  return (
    <div className="space-y-6">
      <div className="rounded-xl border bg-gradient-to-r from-sky-500/10 via-violet-500/5 to-purple-500/10 px-4 py-3 shadow-sm">
        <div className="flex flex-col sm:flex-row sm:items-center gap-3">
          <div className="flex-1">
            <p className="text-sm font-medium">Start from somewhere</p>
            <p className="text-xs text-muted-foreground mt-0.5">
              {hasAi
                ? "Import a recipe from a website, scan a photo, or let AI generate ideas."
                : "Paste a link to a recipe page and Dishes fills in the form."}
            </p>
          </div>
          <div className="flex items-center gap-2 flex-wrap">
            <WebImportModal onImport={handleWebImport} initialUrl={importUrl} />
            {hasAi && (
              <>
                <PhotoImportModal onImport={handlePhotoImport} />
                <AiConcierge onRecipeGenerated={handleRecipeGenerated} />
              </>
            )}
          </div>
        </div>
      </div>

      {webImport && (
        <div className="flex items-start gap-3 rounded-xl bg-gradient-to-r from-sky-500/15 to-cyan-500/10 px-4 py-3 text-sm shadow-sm">
          <Globe className="h-4 w-4 mt-0.5 shrink-0 text-sky-600" />
          <div className="space-y-0.5">
            <p className="font-medium">
              Imported{webImport.host ? ` from ${webImport.host}` : ""} — check it over, then save.
            </p>
            {webImport.via && <p className="text-xs text-muted-foreground">{VIA_LABEL[webImport.via]}</p>}
            {webImport.notice && (
              <p className="flex items-center gap-1 text-xs text-amber-700 dark:text-amber-400">
                <Info className="h-3.5 w-3.5 shrink-0" />
                {webImport.notice}
              </p>
            )}
          </div>
        </div>
      )}

      <RecipeForm
        key={formKey}
        action={createRecipe}
        defaults={defaults}
        heading="New Recipe"
        submitLabel="Create Recipe"
        mode="create"
        defaultImageStyle={defaultImageStyle}
        allTags={allTags}
      />
    </div>
  );
}
